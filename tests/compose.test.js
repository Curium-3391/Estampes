import test from "node:test";
import assert from "node:assert/strict";
import sharp from "sharp";
import { intakeImage,serializeCanvas,restoreCanvas } from "../src/storage.js";
import {createBlankCanvas} from "../src/scene/blank-canvas.js";
import {composeCanvas} from "../src/scene/compose.js";
import {applySceneOps,canvasObjects} from "../src/scene/scene-ops.js";
import {renderCanvas} from "../src/scene/canvas-render.js";
import {canvasLayers,editCanvas,storeUserMarks} from "../src/canvas-state.js";
const pixel=async e=>{const out=await renderCanvas(e,{maxSide:200});return sharp(out.data).removeAlpha().raw().toBuffer();};
test("image layers retain alpha and reorder across raster, marks and editable Graph copies",async()=>{
 const target=await createBlankCanvas({width:200,height:200});
 const source=await intakeImage(await sharp({create:{width:200,height:200,channels:4,background:{r:255,g:0,b:0,alpha:.5}}}).png().toBuffer(),{source:"test"});
 applySceneOps(source,[{op:"object.create",type:"axes-2d",props:{xRange:[-3,3],yRange:[-2,2]}},{op:"object.create",type:"function-plot",props:{frame:"o1",expression:"sin(x)"}}],{author:"user"});
 storeUserMarks(source,[{id:"user-a",type:"point",x:.5,y:.5,label:"source"}]);
 const before=JSON.stringify(serializeCanvas(source));
 await composeCanvas(target,source);
 assert.equal(JSON.stringify(serializeCanvas(source)).replace(/"savedAt":"[^"]+"/,""),before.replace(/"savedAt":"[^"]+"/,""));
 const plot=canvasObjects(target).find(o=>o.type==="function-plot");
 assert.ok(plot);assert.ok(target.objects.has(plot.props.frame));
 applySceneOps(target,[{op:"object.update",id:plot.id,props:{expression:"sin(2*x)"}}],{author:"user"});
 assert.equal(source.objects.get("o2").props.expression,"sin(x)");
 const images=canvasObjects(target).filter(o=>o.type==="image");assert.equal(images.length,2);
 const sourceImage=images.find(o=>o.props.source===source.imageId);
 let data=await pixel(target);assert.ok(data[0]>245&&data[1]>100&&data[1]<180,"alpha blends red with white");
 editCanvas(target,{layers:[{id:sourceImage.layer,opacity:0}]});
 data=await pixel(target);assert.ok(data[0]>245&&data[1]>245,"zero opacity hides image");
 editCanvas(target,{layers:[{id:sourceImage.layer,opacity:1}],order:[sourceImage.layer,...canvasLayers(target).filter(l=>l.id!==sourceImage.layer).map(l=>l.id)]});
 data=await pixel(target);assert.ok(data[0]>245&&data[1]>245,"white base can cover the red image");
 const saved=JSON.parse(JSON.stringify(serializeCanvas(target))),copy={imageId:target.imageId,width:200,height:200};restoreCanvas(copy,saved);
 assert.equal(copy.baseAsObject,true);assert.equal(canvasObjects(copy).length,canvasObjects(target).length);
 assert.deepEqual(await pixel(copy),await pixel(target));
});
test("composition refuses self-copy and rolls back failed layer insertion",async()=>{
 const e=await createBlankCanvas({width:200,height:200});
 await assert.rejects(composeCanvas(e,e),/promotion/);
 await composeCanvas(e);
 const rev=e.sceneRevision;
 await assert.rejects(composeCanvas(e,null,{x:.8,y:0,x2:.1,y2:1}),/positive/);
 assert.equal(e.sceneRevision,rev);
});
