export const GLYPH_WIDTH = 5;
export const GLYPH_HEIGHT = 7;

// Width in glyph pixels of a label (1 pixel spacing between characters).
export const labelWidth = (text) => text.length * (GLYPH_WIDTH + 1) - 1;

// SVG for `text` with its top-left at (x, y), each glyph pixel `px` units,
// on a padded background box so it stays legible over any image.
export function labelSvg(text, x, y, px, { fill = "#111", background = "rgba(255,255,255,.85)" } = {}) {
  const pad = px;
  const parts = [`<rect x="${x}" y="${y}" width="${labelWidth(text) * px + pad * 2}" height="${GLYPH_HEIGHT * px + pad * 2}" fill="${background}"/>`];
  [...text.toUpperCase()].forEach((ch, index) => {
    const glyph = GLYPHS[ch];
    if (!glyph) return;
    const ox = x + pad + index * (GLYPH_WIDTH + 1) * px;
    glyph.forEach((row, ry) => {
      for (let rx = 0; rx < GLYPH_WIDTH; rx++) {
        if (row[rx] === "1") parts.push(`<rect x="${ox + rx * px}" y="${y + pad + ry * px}" width="${px}" height="${px}" fill="${fill}"/>`);
      }
    });
  });
  return parts.join("");
}
